def _admin_pay_orders_where_params(
    *,
    user_id: int = 0,
    status: str = "",
    plan: str = "",
    q: str = "",
) -> tuple[str, list[Any]]:
    """构建 pay_orders 管理端筛选 WHERE 与参数（SQLite / PG 占位符由 connect 适配）。"""
    uid_f = int(user_id or 0)
    st = (status or "").strip()
    pl = (plan or "").strip()
    qq = (q or "").strip()
    clauses: list[str] = []
    params: list[Any] = []
    if uid_f > 0:
        clauses.append("user_id = ?")
        params.append(uid_f)
    if st:
        clauses.append("status = ?")
        params.append(st)
    if pl:
        clauses.append("plan = ?")
        params.append(pl)
    if qq:
        like = f"%{qq}%"
        or_parts = ["out_trade_no LIKE ?", "COALESCE(CAST(transaction_id AS TEXT), '') LIKE ?"]
        params.extend([like, like])
        if qq.isdigit():
            try:
                n = int(qq)
                if n > 0:
                    or_parts.append("user_id = ?")
                    params.append(n)
            except ValueError:
                pass
        clauses.append("(" + " OR ".join(or_parts) + ")")
    where = (" WHERE " + " AND ".join(clauses)) if clauses else ""
    return where, params


